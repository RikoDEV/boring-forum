// A setting without a label of its own is named after its key; scripts/i18n.py puts those
// names in the catalog, so the lookup by text finds a translation.
export const humanize = (/** @type {string} */ key) => {
  if (key.startsWith("plugin:")) {
    const [, plugin, name] = key.split(":");
    return `${name.replaceAll("_", " ")} · ${tr("From plugin {plugin}", { plugin })}`;
  }
  return meta().LABELS[key] ?? tr(key[0].toUpperCase() + key.slice(1).replaceAll("_", " "));
};

/** @type {Map<string, string> | undefined} */
let known;

/** The id of the settings group a key is listed under. */
export const groupOf = (/** @type {string} */ key) =>
  (known ??= new Map(meta().GROUPS.flatMap((g) => g[3].map((k) => [k, g[0]])))).get(key) ??
  (key.startsWith("plugin:") ? "plugins" : "other");

/** The title of a settings group, for a result in the header search. */
export const groupTitle = (id) =>
  meta().GROUPS.find((g) => g[0] === id)?.[1] ?? (id === "plugins" ? tr("From plugins") : tr("Other"));
