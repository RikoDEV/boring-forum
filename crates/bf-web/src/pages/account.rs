//! Sign-in, settings, welcome, shell and legal pages.

use super::{Layout, PageWidgets};
use askama::Template;

#[derive(Template)]
#[template(path = "auth.html")]
pub struct AuthPage {
    pub layout: Layout,
    pub register: bool,
    /// Required documents to accept at registration: (kind, title).
    pub legal: Vec<(String, String)>,
    /// Minimum age; 0 hides the birth date field.
    pub min_age: i64,
    /// Offer sign-in by emailed link.
    pub magic: bool,
    /// External logins: (key, label).
    pub providers: Vec<(&'static str, String)>,
    /// Unix time the form was rendered (time-to-submit check).
    pub ts: String,
    /// Registration questions: (field id, label, kind, options, required, submitted value).
    pub questions: Vec<FieldInput>,
    pub invite_required: bool,
    pub invite: String,
    /// Offer the newsletter (Mailchimp) at sign-up.
    pub newsletter: bool,
    /// (provider, site key) of the registration challenge.
    pub captcha: Option<(String, String)>,
    pub error: Option<String>,
    pub username: String,
    pub email: String,
}

/// A custom profile field as a form input.
pub struct FieldInput {
    pub id: i64,
    pub label: String,
    pub kind: String,
    pub options: Vec<String>,
    pub required: bool,
    pub value: String,
    /// What a link field accepts, shown under the input.
    pub hint: Option<String>,
    /// A link field that also takes a bare name: a text input, so the browser does not refuse it.
    pub shorthand: bool,
}

/// A public custom field on a profile.
pub struct ProfileFieldView {
    pub label: String,
    pub value: String,
    pub icon: Option<String>,
    /// A link field: the value is an http(s) address checked when it was saved.
    pub link: bool,
}

pub struct FormField {
    pub name: &'static str,
    pub label: &'static str,
    pub kind: &'static str,
    pub autocomplete: &'static str,
}

/// Small single-purpose forms: forgot password, reset, two-factor code.
#[derive(Template)]
#[template(path = "form.html")]
pub struct FormPage {
    pub layout: Layout,
    pub heading: String,
    pub message: Option<String>,
    pub error: Option<String>,
    pub action: String,
    pub fields: Vec<FormField>,
    pub button: String,
    pub links: Vec<(&'static str, &'static str)>,
}

pub struct SessionView {
    /// Sprite ids; the flag's country code is lower case and known to exist.
    pub browser_icon: String,
    pub os_icon: String,
    pub id: String,
    pub current: bool,
    pub created: crate::ago::Ago,
    pub last_used: crate::ago::Ago,
    pub ip: Option<String>,
    pub device: Option<String>,
    pub country: Option<String>,
}

/// A freshly generated, not-yet-confirmed TOTP secret.
pub struct TotpSetup {
    pub secret: String,
    pub uri: String,
    /// Inline SVG, when the secret could be encoded as a QR code.
    pub qr: Option<String>,
}

#[derive(Template)]
#[template(path = "settings.html")]
pub struct SettingsPage {
    pub layout: Layout,
    pub quiet_start: String,
    pub quiet_end: String,
    pub username: String,
    pub message: Option<String>,
    pub error: Option<String>,
    pub email: String,
    pub email_verified: bool,
    pub totp_enabled: bool,
    pub totp_setup: Option<TotpSetup>,
    /// How many single-use backup codes are left, once two-factor is on.
    pub backup_codes_left: Option<i64>,
    /// Backup codes just generated by this request; shown once, never stored in plain text.
    pub new_backup_codes: Option<Vec<String>>,
    pub display_name: String,
    pub hide_last_seen: bool,
    pub about: String,
    pub location: String,
    pub website: String,
    pub timezone: String,
    pub profile_visibility: String,
    pub muted_tags: String,
    pub theme_choices: Vec<(i64, String)>,
    pub theme_id: Option<i64>,
    /// Colour schemes a member can pick besides the site's default: (address name, name).
    pub schemes: Vec<(String, String)>,
    /// The site's default scheme, which a member who picked none sees.
    pub default_scheme: (String, String),
    pub keeps_visitors: bool,
    /// When the account is due to be deleted.
    pub deletion_pending: Option<String>,
    /// (id, name, scope, last used)
    pub api_keys: Vec<(i64, String, String, crate::ago::Ago, String)>,
    /// Scopes plugins add to API keys: (scope, label).
    pub plugin_scopes: Vec<(String, String)>,
    /// (kind, label, app, email)
    pub prefs: Vec<(String, String, bool, bool, bool)>,
    pub fields: Vec<FieldInput>,
    pub digest: String,
    /// Mailing-list mode, when the site offers it: whether this member has it on.
    pub mailing_list: Option<bool>,
    /// The newsletter (Mailchimp), when the site has one: whether this member gets it.
    pub newsletter: Option<bool>,
    /// (id, name, created, last used)
    pub passkeys: Vec<(String, String, crate::ago::Ago, crate::ago::Ago)>,
    /// Linked logins: (provider key, label, email, linked).
    pub identities: Vec<(String, String, Option<String>, crate::ago::Ago)>,
    /// False when the account has no other way to sign in, so a linked login cannot be removed.
    pub identity_removable: bool,
    /// Sign-in providers that can still be connected: (provider key, label).
    pub connectable: Vec<(String, String)>,
    /// `everyone`, `following` or `nobody`.
    pub allow_pm_from: String,
    /// Members this one has muted: (id, username).
    pub muted_users: Vec<(i64, String)>,
    /// A member just unmuted: (id, username), offered an undo.
    pub undo_unmute: Option<(i64, String)>,
    /// Devices that skip the second sign-in step.
    pub trusted_devices: i64,
    /// (code, name) of available languages.
    pub locales: Vec<(&'static str, &'static str)>,
    pub sessions: Vec<SessionView>,
}

/// One entry on the getting-started checklist.
pub struct WelcomeStep {
    pub done: bool,
    /// The first step still open, which gets the emphasis.
    pub next: bool,
    pub icon: &'static str,
    pub title: &'static str,
    pub text: &'static str,
    pub action: &'static str,
    pub url: String,
}

#[derive(Template)]
#[template(path = "welcome.html")]
pub struct WelcomePage {
    pub layout: Layout,
    pub name: String,
    pub done: usize,
    pub total: usize,
    pub steps: Vec<WelcomeStep>,
}

/// A page in the shared shell (`http/ui.rs`). `intro`, `actions` and `html` are built by the
/// server from escaped or cooked parts.
#[derive(Template)]
#[template(path = "app.html")]
pub struct AppPage {
    pub layout: Layout,
    /// (url, label) above the heading, from the section's home down.
    pub crumbs: Vec<(String, String)>,
    pub heading: String,
    pub intro: String,
    pub actions: String,
    pub html: String,
    /// Widget areas of this page (`page12`, `db3`), arranged with the layout editor; empty for none.
    pub area: String,
    pub widgets: PageWidgets,
    pub can_edit_layout: bool,
    pub editing_layout: bool,
    /// A custom page's layout; empty for pages that bring their own `html`.
    pub page_template: String,
    pub no_side: bool,
}

#[derive(Template)]
#[template(path = "legal.html")]
pub struct LegalPage {
    pub layout: Layout,
    pub title: String,
    pub updated: crate::ago::Ago,
    pub version: i32,
    /// Cooked by bf-cook.
    pub html: String,
    /// Document ids to accept; empty when only viewing.
    pub accept: Vec<i64>,
}

#[derive(Template)]
#[template(path = "consent.html")]
pub struct ConsentPage {
    pub layout: Layout,
    pub app: String,
    pub write: bool,
    pub client_id: String,
    pub redirect_uri: String,
    pub scope: String,
    pub state: String,
    pub code_challenge: String,
}
