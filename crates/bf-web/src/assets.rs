pub static ISLANDS: LazyLock<Asset> = LazyLock::new(|| {
    Asset::new("islands.js", "text/javascript; charset=utf-8", include_bytes!(concat!(env!("OUT_DIR"), "/islands.js")))
});

/// What every page's script needs before it can run: the islands entry and the chunks it imports
/// outright. Preloaded, the browser fetches them side by side instead of finding each one only
/// after the file before it has arrived.
pub static SCRIPT_PRELOADS: LazyLock<Vec<String>> = LazyLock::new(|| {
    let entry = std::str::from_utf8(ISLANDS.body).unwrap_or_default();
    let imports = CHUNKS.iter().filter(|(name, _)| entry.contains(&format!("from\"./{name}\"")));
    std::iter::once(ISLANDS.url()).chain(imports.map(|(name, _)| format!("/assets/{name}"))).collect()
});

pub static EDITOR: LazyLock<Asset> = LazyLock::new(|| {
    Asset::new("editor.js", "text/javascript; charset=utf-8", include_bytes!(concat!(env!("OUT_DIR"), "/editor.js")))
});

pub static MEMBERS: LazyLock<Asset> = LazyLock::new(|| {
    Asset::new("members.js", "text/javascript; charset=utf-8", include_bytes!(concat!(env!("OUT_DIR"), "/members.js")))
});

fn all() -> [&'static Asset; 6] {
    [&CSS, &ISLANDS, &EDITOR, &MEMBERS, &ICONS, &BRANDS]
}

// Generated by build.rs: the island chunks, `(file name, bytes)`. The names already carry a
// content hash from the bundler.
include!(concat!(env!("OUT_DIR"), "/chunks.rs"));

pub async fn serve(Path(file): Path<String>, headers: HeaderMap) -> Response {
    let found = match all().into_iter().find(|a| a.hashed == file) {
        Some(a) => Some((a.hashed.as_str(), a.mime, a.body)),
        None => CHUNKS.iter().find(|(n, _)| *n == file).map(|(n, b)| (*n, "text/javascript; charset=utf-8", *b)),
    };
    let Some((name, mime, body)) = found else {
        return StatusCode::NOT_FOUND.into_response();
    };
    let etag = format!("\"{name}\"");
    if headers.get(header::IF_NONE_MATCH).is_some_and(|v| v.as_bytes() == etag.as_bytes()) {
        return StatusCode::NOT_MODIFIED.into_response();
    }
    (
        [
            (header::CONTENT_TYPE, mime.to_owned()),
            (header::CACHE_CONTROL, "public, max-age=31536000, immutable".to_owned()),
            (header::ETAG, etag),
        ],
        body,
    )
        .into_response()
}

