//! Static assets embedded in the binary and served under content-hashed names
//! with `Cache-Control: immutable`.

use axum::extract::Path;
use axum::http::{HeaderMap, StatusCode, header};
use axum::response::{IntoResponse, Response};
use std::sync::LazyLock;

pub struct Asset {
    pub name: &'static str,
    pub mime: &'static str,
    pub body: &'static [u8],
    /// `name.HASH.ext`, the path the templates link to.
    pub hashed: String,
}

impl Asset {
    fn new(name: &'static str, mime: &'static str, body: &'static [u8]) -> Self {
        let (stem, ext) = name.rsplit_once('.').unwrap_or((name, ""));
        let hashed = format!("{stem}.{:016x}.{ext}", fnv1a(body));
        Self { name, mime, body, hashed }
    }

    pub fn url(&self) -> String {
        format!("/assets/{}", self.hashed)
    }
}

/// FNV-1a: a small, stable content hash. Cache busting needs uniqueness, not secrecy.
fn fnv1a(bytes: &[u8]) -> u64 {
    bytes.iter().fold(0xcbf2_9ce4_8422_2325, |h, b| (h ^ u64::from(*b)).wrapping_mul(0x0100_0000_01b3))
}

